"""Generate reviewed fallback labels; never imports or copies a game localization."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root/'translations/content.zh-CN.json').read_text(encoding='utf-8'))
lines = ['#pragma once', '// Generated by tools/generate-zh-content.py from reviewed fallback translations.',
         'namespace sco_zh {', 'struct NamePair { const char* from; const char* to; };']
for group, name in [('exact', 'kContentExact'), ('tokens', 'kContentTokens')]:
    lines.append(f'inline constexpr NamePair {name}[] = {{')
    seen = set()
    for key, value in sorted(catalog[group].items()):
        lower = key.lower()
        if lower in seen:
            raise ValueError(f'Duplicate case-insensitive key: {key}')
        seen.add(lower)
        lines.append('    {'+json.dumps(lower, ensure_ascii=False)+', '+json.dumps(value, ensure_ascii=False)+'},')
    lines.append('};')
lines.append('} // namespace sco_zh\n')
(root/'src/zh/content_catalog.generated.h').write_text('\n'.join(lines), encoding='utf-8')
print('Generated',len(catalog['exact']),'exact and',len(catalog['tokens']),'token translations')
